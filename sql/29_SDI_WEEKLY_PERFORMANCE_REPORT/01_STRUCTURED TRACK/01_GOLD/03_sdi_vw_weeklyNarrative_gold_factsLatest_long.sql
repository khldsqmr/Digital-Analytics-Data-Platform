/* FILE 03 — Newest one snapshot per Saturday, explicit 59-field contract.
   Original column comments preserved from the factsHistory table definition.
   Published reports must pin snapshot_id and query history, NOT this live latest view. */
CREATE OR REPLACE VIEW prdrzranalytics.lab42.sdi_vw_weeklyNarrative_gold_factsLatest_long
(
  snapshot_id COMMENT 'Snapshot identifier, WN_FACTS_yyyyMMdd_HHmmss_SSS_uuid. One per procedure run. Published reports pin this value.',
  snapshot_ts COMMENT 'When the snapshot was taken (UTC).',
  run_type COMMENT 'JOB = scheduled Databricks Job run. MANUAL = interactive or ad hoc call (including backfills).',
  job_run_id COMMENT 'Databricks Job Run ID for JOB runs; the snapshot_id for MANUAL runs.',
  week_end COMMENT 'Reporting week end date. Always a Saturday; the week runs Sunday to Saturday.',
  week_type COMMENT 'From the PulseTMS QGP calendar: NORMAL or BOUNDARY_FIRST. BOUNDARY_FIRST = first Saturday after a quarter end that fell mid-week.',
  qgp_quarter COMMENT 'QGP quarter label of week_end, e.g. 2026 Q4.',
  days_in_period COMMENT 'Days in the QGP period ending on week_end: 7 for NORMAL, fewer for BOUNDARY_FIRST. Explains why metric_value can be partial.',
  is_complete_period COMMENT 'Calendar completeness flag from the PulseTMS QGP calendar. Does NOT guarantee every source has settled; see is_data_current and source_validation_status.',
  registry_version COMMENT 'registry_version of sdi_vw_weeklyNarrative_control_metricRegistry_static used for this snapshot.',
  metric_key COMMENT 'Registry primary key of the metric slice.',
  display_name COMMENT 'Report-facing metric name from the registry.',
  metric_lob COMMENT 'LOB(s) the metric covers, from the registry: one LOB (POSTPAID, BROADBAND, BYOD, FIBER, TFB, METRO) or several joined with + (e.g. POSTPAID + BROADBAND). NULL = metric has no LOB (e.g. total site UPV, store traffic). Group the report by this.',
  sort_order COMMENT 'Report display order from the registry.',
  row_role COMMENT 'ACTUAL = the metric at its own channel_group (what the report writes about). ACTUAL_DRIVER = same metric at another channel_group, used to explain moves. TARGET = forecast or QGP target row. TARGET_DRIVER = channel-level forecast or target.',
  source_project COMMENT 'Code of the upstream project the numbers come from: PULSE_TMS. weeklyNarrative only reads these values, it never recomputes them.',
  source_object COMMENT 'Fully qualified upstream object read for this row: prdrzranalytics.lab42.sdi_vw_dashboardPulseTms_gold_unified_long (PulseTMS Gold).',
  data_source COMMENT 'PulseTMS Gold data_source the row came from.',
  metric_name COMMENT 'PulseTMS Gold metric_name the row came from.',
  metric_type COMMENT 'PulseTMS Gold metric_type the row came from.',
  source_lob COMMENT 'PulseTMS Gold true_lob value(s) read for this row, from the registry. NULL = source has no LOB (ADOBE, UPV_FORECAST, some QGP). One value = single LOB. Several joined with + (e.g. POSTPAID + BROADBAND) = summed total.',
  is_lob_rollup_complete COMMENT 'Only when source_lob lists several LOBs: TRUE when every one had a value this week. FALSE means the total is partial and must not be reported as a full total. NULL for single-LOB or no-LOB rows.',
  channel_group COMMENT 'PulseTMS Gold channel_group. Headline rows are normally All Channels; ACTUAL_DRIVER rows carry the individual channel. NULL for QGP_SCORECARD.',
  unit COMMENT 'COUNT | USD | PCT. PCT values are ratios (0.31 = 31%).',
  higher_is_better COMMENT 'Direction of good performance from the registry. NULL = neutral.',
  metric_value COMMENT 'PulseTMS Gold metric_value for the QGP period ending week_end, unchanged. Partial on BOUNDARY_FIRST weeks. Kept for traceability; report on week_value instead.',
  week_value COMMENT 'Value for the full Sunday-Saturday week, built from the Gold periods inside it: NORMAL = its 7-day period; BOUNDARY_FIRST = quarter-end stub + new-quarter piece (sum for COUNT/USD, day-weighted average for PCT). If a boundary piece is missing: UPV_FORECAST estimates the missing days from the other piece daily rate, QGP_SCORECARD gives NULL, spend and Adobe count it as 0. Use this in the narrative.',
  prior_week_value COMMENT 'week_value of the week ending 7 days earlier (same boundary-safe build).',
  wow_pct COMMENT 'Week-over-week change as a ratio (0.12 = +12%): week_value / prior_week_value - 1. Computed here (not PulseTMS wow_pct) so boundary weeks and the week after them are correct.',
  ly_week_value COMMENT 'PulseTMS Gold yoy_denominator: same ISO week last year, full weekly total.',
  yoy_pct COMMENT 'Year-over-year change as a ratio (0.04 = +4%). PulseTMS Gold yoy_pct for single-LOB rows; recomputed from summed numerators and denominators for LOB rollup rows. NULL where prior-year history does not exist (e.g. Programmatic, Fiber).',
  target_metric_key COMMENT 'Registry key of the target this row is compared against: the forecast for MFC spend and UPV, the QGP target for QGP metrics. NULL if none.',
  target_week_value COMMENT 'Target for the same week_end and channel_group (full Sunday-Saturday week). NULL if no target or not populated.',
  vs_target_abs COMMENT 'Actual minus target: week_value - target_week_value. For unit = PCT, the gap in points as a ratio (0.02 = 2 pts).',
  vs_target_pct COMMENT 'Actual vs target as a ratio: week_value / target_week_value - 1 (-0.03 = 3% below target). NULL for unit = PCT.',
  is_target_same_as_actual COMMENT 'TRUE when target equals actual exactly. For MFC this means PulseTMS filled a missing forecast with the actual (week-level fallback in MFC Bronze), so the narrative must say no target was available, not on target. NULL when there is no target.',
  avg_prior_4wk COMMENT 'Average weekly value of the 4 full weeks before week_end (current week excluded).',
  avg_prior_13wk COMMENT 'Average weekly value of the 13 full weeks (about one quarter) before week_end.',
  avg_prior_52wk COMMENT 'Average weekly value of the 52 full weeks (about one year) before week_end.',
  stddev_prior_13wk COMMENT 'Sample standard deviation of weekly values over the 13 weeks before week_end: the metric normal weekly swing.',
  prior_52wk_weeks COMMENT 'Number of weeks with data in the 52-week window. Below 52 means short history and a weaker average.',
  vs_avg_prior_4wk COMMENT 'week_value vs avg_prior_4wk. Ratio for COUNT/USD (0.08 = 8% above average); points for PCT (0.01 = 1 pt).',
  vs_avg_prior_13wk COMMENT 'week_value vs avg_prior_13wk. Ratio for COUNT/USD; points for PCT.',
  vs_avg_prior_52wk COMMENT 'week_value vs avg_prior_52wk. Ratio for COUNT/USD; points for PCT.',
  zscore_prior_13wk COMMENT '(week_value - avg_prior_13wk) / stddev_prior_13wk. How unusual this week is versus normal swing; |z| >= 2 is a strong highlight candidate.',
  mtd_avg_weekly COMMENT 'Month-to-date average per 7 days, for weeks ending in the calendar month of week_end. PCT: day-weighted average ratio.',
  qtd_avg_weekly COMMENT 'QGP quarter-to-date average per 7 days, quarter-boundary exact. PCT: day-weighted average ratio.',
  ytd_avg_weekly COMMENT 'Year-to-date average per 7 days, year-boundary exact. PCT: day-weighted average ratio.',
  mtd_total COMMENT 'Month-to-date total (weeks ending in the month of week_end). NULL for PCT.',
  qtd_total COMMENT 'QGP quarter-to-date total through week_end, quarter-boundary exact. NULL for PCT.',
  ytd_total COMMENT 'Year-to-date total through week_end. NULL for PCT.',
  qtd_target_avg_weekly COMMENT 'Quarter-to-date target, average per 7 days (same channel_group), over the same periods as the actual (periods with no actual are left out).',
  qtd_target_total COMMENT 'Quarter-to-date target total over the periods where the actual has a value, so it is comparable to qtd_total. NULL for PCT.',
  qtd_vs_target COMMENT 'Quarter-to-date pacing vs target. COUNT/USD: qtd_total / qtd_target_total - 1 (ratio). PCT: qtd_avg_weekly - qtd_target_avg_weekly (points).',
  max_date COMMENT 'Latest qgp_date with a non-null value for this metric in PulseTMS Gold at snapshot time (PulseTMS Gold max_date). For LOB rollups, the earliest max_date of the member LOBs.',
  is_data_current COMMENT 'TRUE when max_date >= week_end, i.e. the source has reported through this week. FALSE flags reporting lag (common for QGP actuals).',
  source_validation_run_id COMMENT 'Latest PulseTMS validation run (sdi_vw_dashboardPulseTms_validation_runs_perRun) for the same data_as_of_date as week_end. NULL if no validation ran for that week (e.g. backfills).',
  source_validation_status COMMENT 'PulseTMS validation status (sdi_vw_dashboardPulseTms_validation_summary_perRun) for this row data source in that run: Healthy, Warning or Failed. NULL when no run exists.',
  created_ts COMMENT 'Row insert timestamp.'
)
COMMENT 'Latest snapshot identity per week; drafting only. Reports pin the factsHistory snapshot_id.'
AS WITH SnapshotKeys AS (
  SELECT DISTINCT week_end,snapshot_id,snapshot_ts
  FROM prdrzranalytics.lab42.sdi_tbl_weeklyNarrative_gold_factsHistory_long
), Latest AS (
  SELECT week_end,snapshot_id
  FROM SnapshotKeys
  QUALIFY ROW_NUMBER() OVER (PARTITION BY week_end ORDER BY snapshot_ts DESC,snapshot_id DESC)=1
)
SELECT
  h.snapshot_id,
  h.snapshot_ts,
  h.run_type,
  h.job_run_id,
  h.week_end,
  h.week_type,
  h.qgp_quarter,
  h.days_in_period,
  h.is_complete_period,
  h.registry_version,
  h.metric_key,
  h.display_name,
  h.metric_lob,
  h.sort_order,
  h.row_role,
  h.source_project,
  h.source_object,
  h.data_source,
  h.metric_name,
  h.metric_type,
  h.source_lob,
  h.is_lob_rollup_complete,
  h.channel_group,
  h.unit,
  h.higher_is_better,
  h.metric_value,
  h.week_value,
  h.prior_week_value,
  h.wow_pct,
  h.ly_week_value,
  h.yoy_pct,
  h.target_metric_key,
  h.target_week_value,
  h.vs_target_abs,
  h.vs_target_pct,
  h.is_target_same_as_actual,
  h.avg_prior_4wk,
  h.avg_prior_13wk,
  h.avg_prior_52wk,
  h.stddev_prior_13wk,
  h.prior_52wk_weeks,
  h.vs_avg_prior_4wk,
  h.vs_avg_prior_13wk,
  h.vs_avg_prior_52wk,
  h.zscore_prior_13wk,
  h.mtd_avg_weekly,
  h.qtd_avg_weekly,
  h.ytd_avg_weekly,
  h.mtd_total,
  h.qtd_total,
  h.ytd_total,
  h.qtd_target_avg_weekly,
  h.qtd_target_total,
  h.qtd_vs_target,
  h.max_date,
  h.is_data_current,
  h.source_validation_run_id,
  h.source_validation_status,
  h.created_ts
FROM prdrzranalytics.lab42.sdi_tbl_weeklyNarrative_gold_factsHistory_long h
JOIN Latest l ON h.week_end=l.week_end AND h.snapshot_id=l.snapshot_id;
